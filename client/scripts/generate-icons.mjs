#!/usr/bin/env node
// Regenerate the desktop app icon set and the tray icons from their sources.
//
//   bun run icons                       # uses src-tauri/icons/source/*.png
//   bun run icons -- --app my-logo.png  # one-off override of the app source
//
// To swap the artwork: overwrite src-tauri/icons/source/app-icon.png (square,
// >= 1024 px, transparent corners) and source/tray-icon.png, then run
// `bun run icons` and commit the result.
//
// App icons are produced by the official Tauri CLI (`tauri icon`). Only the
// files that tauri.conf.json (bundle.icon) references are kept; the CLI's
// iOS/Windows-Store extras are discarded because no bundle target uses them.
// Tray icons, the web favicon/apple-touch icon and the Android launcher icons
// (mobile/android) are resized with sharp.

import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const clientDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const iconsDir = join(clientDir, "src-tauri", "icons");
const trayDir = join(iconsDir, "tray");
const publicDir = join(clientDir, "public");
const androidResDir = join(clientDir, "..", "mobile", "android", "app", "src", "main", "res");

/** Files kept from the `tauri icon` output (must match tauri.conf.json). */
const APP_FILES = [
  "32x32.png",
  "64x64.png",
  "128x128.png",
  "128x128@2x.png",
  "icon.png",
  "icon.icns",
  "icon.ico",
];

/** Tray icon sizes (px): 32 for standard DPI, 64 for HiDPI panels. */
const TRAY_SIZES = [32, 64];

/** Entries of the web favicon.ico (px). */
const FAVICON_SIZES = [16, 32, 48];

/** Android density buckets and their scale relative to mdpi. */
const ANDROID_DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

/** Legacy launcher icon (dp) and adaptive-icon layer (dp) sizes. */
const ANDROID_LEGACY_DP = 48;
const ANDROID_ADAPTIVE_DP = 108;

/**
 * Diameter (dp) of the round badge on the adaptive foreground. Launchers show
 * the centre 72 dp of the 108 dp layer and guarantee only a 66 dp circle;
 * 66 dp keeps the whole badge inside any mask, the background fills the rest.
 */
const ANDROID_BADGE_DP = 66;

/** Adaptive-icon background: the badge's own dark fill, so masks blend in. */
const ANDROID_BACKGROUND = "#2F3744";

function resizedPng(source, size) {
  return sharp(source)
    .resize(size, size, { fit: "contain", kernel: "lanczos3" })
    .png({ compressionLevel: 9 });
}

/** Pack PNG images into an .ico container (PNG-compressed entries). */
function packIco(pngs) {
  const header = Buffer.alloc(6 + pngs.length * 16);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, data }, i) => {
    const e = 6 + i * 16;
    header[e] = size; // width (< 256)
    header[e + 1] = size; // height
    header.writeUInt16LE(1, e + 4); // colour planes
    header.writeUInt16LE(32, e + 6); // bits per pixel
    header.writeUInt32LE(data.length, e + 8);
    header.writeUInt32LE(offset, e + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...pngs.map((p) => p.data)]);
}

async function writeAndroidIcons(source) {
  for (const [density, scale] of Object.entries(ANDROID_DENSITIES)) {
    const dir = join(androidResDir, `mipmap-${density}`);
    mkdirSync(dir, { recursive: true });
    const legacy = Math.round(ANDROID_LEGACY_DP * scale);
    await resizedPng(source, legacy).toFile(join(dir, "ic_launcher.png"));
    await resizedPng(source, legacy).toFile(join(dir, "ic_launcher_round.png"));

    const layer = Math.round(ANDROID_ADAPTIVE_DP * scale);
    const badge = Math.round(ANDROID_BADGE_DP * scale);
    const inset = Math.floor((layer - badge) / 2);
    await sharp({
      create: { width: layer, height: layer, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
    })
      .composite([{ input: await resizedPng(source, badge).toBuffer(), left: inset, top: inset }])
      .png({ compressionLevel: 9 })
      .toFile(join(dir, "ic_launcher_foreground.png"));
  }

  const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by client/scripts/generate-icons.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
`;
  const anydpi = join(androidResDir, "mipmap-anydpi-v26");
  mkdirSync(anydpi, { recursive: true });
  writeFileSync(join(anydpi, "ic_launcher.xml"), adaptive);
  writeFileSync(join(anydpi, "ic_launcher_round.xml"), adaptive);
  writeFileSync(
    join(androidResDir, "values", "ic_launcher_background.xml"),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by client/scripts/generate-icons.mjs. -->
<resources>
    <color name="ic_launcher_background">${ANDROID_BACKGROUND}</color>
</resources>
`,
  );
}

function argValue(flag) {
  const i = process.argv.indexOf(flag);
  return i === -1 ? undefined : process.argv[i + 1];
}

const appSource = resolve(argValue("--app") ?? join(iconsDir, "source", "app-icon.png"));
const traySource = resolve(argValue("--tray") ?? join(iconsDir, "source", "tray-icon.png"));

const work = mkdtempSync(join(tmpdir(), "kaiku-icons-"));
try {
  const run = spawnSync("bunx", ["tauri", "icon", appSource, "-o", work], {
    cwd: clientDir,
    stdio: ["ignore", "ignore", "inherit"],
  });
  if (run.status !== 0) {
    throw new Error(`tauri icon failed (exit ${run.status})`);
  }
  for (const f of APP_FILES) {
    copyFileSync(join(work, f), join(iconsDir, f));
  }

  mkdirSync(trayDir, { recursive: true });
  for (const size of TRAY_SIZES) {
    await resizedPng(traySource, size).toFile(join(trayDir, `${size}x${size}.png`));
  }

  const favicons = await Promise.all(
    FAVICON_SIZES.map(async (size) => ({ size, data: await resizedPng(appSource, size).toBuffer() })),
  );
  writeFileSync(join(publicDir, "favicon.ico"), packIco(favicons));
  await resizedPng(appSource, 180).toFile(join(publicDir, "apple-touch-icon.png"));
  await writeAndroidIcons(appSource);
  console.log(`Icons written to ${iconsDir}, ${publicDir} and ${androidResDir}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
