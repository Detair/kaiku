package io.wolftown.kaiku.approval

import io.wolftown.kaiku.domain.model.ApprovalChallenge
import io.wolftown.kaiku.testutil.Golden
import io.wolftown.kaiku.testutil.SigFixtures
import io.wolftown.kaiku.testutil.SigFixtures.hex
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import kotlinx.serialization.json.long
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayOutputStream
import java.nio.ByteBuffer

/**
 * C26 golden vectors as the server writes them (L1a's
 * `golden/kaiku_sig_v1.json`, generated by the server's own encoder; read only).
 * For each vector the app rebuilds C, `context_hash`, the signing prefix and M
 * from the inputs, compares them with the file, verifies the signature with the
 * file's public key and runs its own pre-UV checks on the server's bytes.
 * [Golden.load] fails if the file is missing, so a lost file fails the build.
 * `KaikuSigGoldenTest` keeps the same vectors from the contract text.
 */
class KaikuSigGoldenFileTest {

    private val file: JsonObject = Json.parseToJsonElement(Golden.load("kaiku_sig_v1.json")).jsonObject
    private val publicKey = file.str("public_key")
    private val vectors = file["vectors"]!!.jsonArray.map { it.jsonObject }

    @Test fun `the file is version 1 with the five C26 vectors`() {
        assertEquals(1, file["version"]!!.jsonPrimitive.int)
        assertEquals(listOf("V01", "V02", "V03", "V04", "V05"), vectors.map { it.str("name") })
        assertEquals(
            listOf("login", "enroll", "device_login", "device_stepup", "enroll_pop"),
            vectors.map { it.str("kind") },
        )
    }

    @Test fun `canonical context and context hash match the server`() {
        vectors.forEach { v ->
            val ctx = SigContext.fromJson(kind(v), v["context"]!!.jsonObject)
            assertEquals(v.str("name"), v.str("c_hex"), ctx.canonical().hex())
            assertEquals(v.str("name"), v.str("context_hash_hex"), KaikuSig.contextHash(ctx).hex())
        }
    }

    @Test fun `signing prefix built from the inputs matches the server and parses back`() {
        vectors.forEach { v ->
            val name = v.str("name")
            val prefix = prefixFrom(v)
            assertArrayEquals(name, SigFixtures.unb64u(v.str("signing_prefix_b64u")), prefix)
            val parsed = KaikuSig.parsePrefix(prefix)
            assertEquals(name, kind(v).byte, parsed.kind)
            assertEquals(name, v.str("challenge_id"), parsed.challengeId)
            assertEquals(name, v.str("nonce_hex"), parsed.nonce.hex())
            assertEquals(name, v["expires_at"]!!.jsonPrimitive.long, parsed.expiresAt)
            assertEquals(name, v.str("origin"), parsed.origin)
            assertEquals(name, v.str("user_id"), parsed.userId)
            assertEquals(name, v.str("device_id"), parsed.deviceId)
            assertEquals(name, v.str("context_hash_hex"), parsed.contextHash.hex())
        }
    }

    @Test fun `message matches the server and the signature verifies`() {
        vectors.forEach { v ->
            val name = v.str("name")
            val m = KaikuSig.message(prefixFrom(v), decision(v), SigFixtures.unhex(v.str("response_hex")))
            assertEquals(name, v.str("message_hex"), m.hex())
            assertTrue(name, SigFixtures.verifyP256(publicKey, m, v.str("signature")))
        }
    }

    @Test fun `the pre-UV checks accept every server vector at its own origin`() {
        vectors.forEach { v ->
            val expiresAt = v["expires_at"]!!.jsonPrimitive.long
            val checks = ChallengeVerifier({ v.str("origin") }, { expiresAt - 30 })
            val ch = ApprovalChallenge(
                challengeId = v.str("challenge_id"),
                kind = v.str("kind"),
                variant = v["variant"]?.takeUnless { it is kotlinx.serialization.json.JsonNull }?.jsonPrimitive?.content,
                expiresAt = java.time.Instant.ofEpochSecond(expiresAt).toString(),
                signingPrefix = v.str("signing_prefix_b64u"),
                context = v["context"]!!.jsonObject,
            )
            val verified = checks.verify(ch, kind(v), v.str("user_id"), v.str("device_id"))
            assertEquals(v.str("name"), v.str("challenge_id"), verified.challengeId)
        }
    }

    private fun JsonObject.str(key: String): String = this[key]!!.jsonPrimitive.content

    private fun kind(v: JsonObject): SigKind = SigKind.entries.first { it.wire == v.str("kind") }

    private fun decision(v: JsonObject): Decision = Decision.entries.first { it.wire == v.str("decision") }

    /** C26 "Prefix layout", from the vector's inputs only (never from its own prefix). */
    private fun prefixFrom(v: JsonObject): ByteArray {
        val ctx = SigContext.fromJson(kind(v), v["context"]!!.jsonObject)
        return ByteArrayOutputStream().apply {
            write(KaikuSig.MAGIC.toByteArray(Charsets.US_ASCII))
            write(kind(v).byte)
            write(KaikuSig.uuidBytes(v.str("challenge_id")))
            write(SigFixtures.unhex(v.str("nonce_hex")))
            write(ByteBuffer.allocate(8).putLong(v["expires_at"]!!.jsonPrimitive.long).array())
            write(KaikuSig.lp(v.str("origin").toByteArray(Charsets.US_ASCII)))
            write(KaikuSig.uuidBytes(v.str("user_id")))
            write(KaikuSig.uuidBytes(v.str("device_id")))
            write(KaikuSig.contextHash(ctx))
        }.toByteArray()
    }
}
